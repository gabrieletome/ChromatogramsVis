library(shinytest2)

test_that("{shinytest2} recording: ChromatogramsVis", {
    appdir <- system.file(package = "ChromatogramsVis", "app")
    local_app_support(test_path(appdir))
    app <- AppDriver$new(test_path(appdir), variant = platform_variant(),
                name = "ChromatogramVis", height = 959, width = 1560)
    Sys.sleep(2)
    app$expect_screenshot()
    app$set_inputs(input_cat = "R object")
    app$set_inputs(load_in_memory = TRUE)
    app$upload_file(rds_file = system.file("rds","test_example.rds", package = "ChromatogramsVis"))
    Sys.sleep(2)
    app$expect_screenshot()
    app$click("load_rds_file")
    app$set_inputs(tabs = "chr")
    app$set_inputs(`chromatogramsPlot-chr_color` = "#00000080")
    app$set_inputs(`chromatogramsPlot-chr_xlim` = c(11, 57.5))
    app$set_inputs(`chromatogramsPlot-chr_ylim` = c(50.5, 2472.015))
    app$set_inputs(`chromatogramsPlot-slider` = 1)
    app$set_inputs(`chromatogramsPlot-chr_bs` = 16)
    app$set_inputs(`chromatogramsPlot-chr_pch` = 20)
    app$set_inputs(`chromatogramsPlot-chr_cex` = 3)
    app$set_inputs(`chromatogramsPlot-chr_lwd` = 0.5)
    Sys.sleep(2)
    app$expect_screenshot()
    app$set_inputs(`chromatogramsPlot-chr_xlim` = c(11, 21.5))
    app$set_inputs(`chromatogramsPlot-chr_ylim` = c(50.5, 2350))
    app$set_inputs(`chromatogramsPlot-chr_ylim` = c(50.5, 2411))
    app$set_inputs(`chromatogramsPlot-chr_color` = "#B0232380")
    app$set_inputs(`chromatogramsPlot-chr_bs` = 17)
    app$set_inputs(`chromatogramsPlot-chr_pch` = 16)
    app$set_inputs(`chromatogramsPlot-chr_cex` = 6)
    app$set_inputs(`chromatogramsPlot-chr_lwd` = 1)
    Sys.sleep(2)
    app$expect_screenshot()
    Sys.sleep(2)
    app$expect_download("chromatogramsPlot-downloadChromatograms")
    Sys.sleep(5)
    rds_path <- app$get_download(
                                "chromatogramsPlot-downloadChromatograms_RDS")
    rds_obj <- readRDS(rds_path)
    expect_s4_class(rds_obj, "Chromatograms")
    app$set_inputs(tabs = "chr_overlay")
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_color` = "#00000080")
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_col_method` = "Single color")
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_xlim` = c(11, 57.5))
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_ylim` = c(50.5, 2472.015))
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_showAxes` = TRUE)
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_showBox` = TRUE)
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_bs` = 16)
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_pch` = 20)
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_cex` = 3)
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_lwd` = 0.5)
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_idx` = "1-2")
    Sys.sleep(2)
    app$expect_screenshot()
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_xlim` = c(11, 57))
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_xlim` = c(11, 56.5))
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_ylim` = c(151, 2472.015))
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_bs` = 15)
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_pch` = 19)
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_cex` = 6)
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_lwd` = 1)
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_showAxes` = FALSE)
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_showAxes` = TRUE)
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_showBox` = FALSE)
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_showBox` = TRUE)
    Sys.sleep(2)
    app$expect_screenshot()
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_col_method` = "Auto multiple colors")
    Sys.sleep(2)
    app$expect_screenshot()
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_col_method` = "Manual colors")
    Sys.sleep(2)
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_col_method` = "Auto multiple colors")
    Sys.sleep(2)
    app$expect_download("chromatogramsOverlayPlot-downloadChromatograms_overlay")
    Sys.sleep(5)
    rds_path <- app$get_download(
                "chromatogramsOverlayPlot-downloadChromatograms_overlay_RDS")
    rds_obj <- readRDS(rds_path)
    expect_s4_class(rds_obj, "Chromatograms")
    app$set_inputs(`chromatogramsOverlayPlot-chrOverlay_idx` = "1")
    Sys.sleep(2)
    app$expect_screenshot()
})
